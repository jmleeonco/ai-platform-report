/* Client-side search for the report index (root index.html).
   Loads data/search-index.json — regenerated by the report server on every write,
   one entry per topic (k:"topic") and per experiment (k:"exp") — plus
   data/topics-meta.json, and live-filters as you type. No dependencies. */
(function () {
  var box = document.getElementById("search");
  var results = document.getElementById("search-results");
  var grid = document.querySelector(".card-grid");
  var counter = document.getElementById("search-count");
  if (!box || !results) return;

  var DATA = [];
  // metadata (status/owner/category/keywords/branch/edited) lives in data/topics-meta.json —
  // load it and flatten each topic's values into a per-slug searchable string so ALL
  // metadata is searchable without baking it into the index.
  var BASE = "topics/";   // pages live under topics/; data + index.html are at the site root
  Promise.all([
    fetch("data/search-index.json").then(function (r) { return r.json(); }),
    fetch("data/topics-meta.json").then(function (r) { return r.json(); }).catch(function () { return {}; })
  ]).then(function (res) {
    DATA = res[0];
    var META = res[1] || {};
    var bySlug = {};
    for (var slug in META) {
      var vals = [];
      for (var k in META[slug]) { var v = META[slug][k]; vals.push(Array.isArray(v) ? v.join(" ") : v); }
      bySlug[slug] = vals.join(" ");
    }
    for (var i = 0; i < DATA.length; i++) { DATA[i].s = bySlug[DATA[i].u.split("/")[0]] || ""; }
    box.disabled = false; box.placeholder = "Search topics & experiments…";
    if (pending) run(pending);
  }).catch(function () { box.placeholder = "Search index unavailable"; });

  var pending = "";
  function esc(s) { return s.replace(/[&<>"]/g, function (c) { return ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]; }); }

  function snippet(text, tokens) {
    var low = text.toLowerCase(), at = -1;
    for (var i = 0; i < tokens.length; i++) { var p = low.indexOf(tokens[i]); if (p !== -1 && (at === -1 || p < at)) at = p; }
    if (at === -1) return "";
    var start = Math.max(0, at - 50), end = Math.min(text.length, at + 130);
    var s = (start > 0 ? "… " : "") + text.slice(start, end) + (end < text.length ? " …" : "");
    return esc(s);
  }

  function run(q) {
    pending = q;
    if (!DATA.length) return;
    q = q.trim().toLowerCase();
    if (!q) { results.hidden = true; results.innerHTML = ""; if (grid) grid.hidden = false; if (counter) counter.textContent = ""; return; }
    if (grid) grid.hidden = true;
    var tokens = q.split(/\s+/).filter(Boolean);
    var hits = [];
    for (var i = 0; i < DATA.length; i++) {
      var e = DATA[i];
      var title = e.t.toLowerCase(), topic = (e.p || "").toLowerCase(),
          smeta = (e.s || "").toLowerCase(), text = (e.x || "").toLowerCase();
      var ok = true, score = 0;
      for (var j = 0; j < tokens.length; j++) {
        var tk = tokens[j];
        if (title.indexOf(tk) !== -1) score += 100;
        else if (topic.indexOf(tk) !== -1) score += 40;
        else if (smeta.indexOf(tk) !== -1) score += 30;   // status/owner/category/keywords/branch
        else if (text.indexOf(tk) !== -1) score += 10;
        else { ok = false; break; }
      }
      if (ok) { if (e.k === "topic") score += 5; hits.push([score, e]); }
    }
    hits.sort(function (a, b) { return b[0] - a[0]; });
    if (counter) counter.textContent = hits.length + " result" + (hits.length === 1 ? "" : "s");
    var max = Math.min(hits.length, 60);
    var html = "";
    for (var k = 0; k < max; k++) {
      var e2 = hits[k][1];
      var kind = e2.k === "topic" ? "topic" : "experiment";
      var crumb = e2.k === "topic" ? "Topic" : esc(e2.p);
      if (e2.s) crumb += '  ·  ' + esc(e2.s);
      var sn = snippet((e2.x || "") + " " + (e2.s || ""), tokens);
      html += '<a class="sr-row" href="' + BASE + e2.u + '">' +
        '<span class="sr-kind ' + kind + '">' + kind + "</span>" +
        '<span class="sr-body"><span class="sr-title">' + esc(e2.t) + "</span>" +
        '<span class="sr-crumb">' + crumb + "</span>" +
        (sn ? '<span class="sr-snippet">' + sn + "</span>" : "") +
        "</span></a>";
    }
    if (!max) html = '<div class="sr-empty">No matches.</div>';
    else if (hits.length > max) html += '<div class="sr-more">Showing ' + max + " of " + hits.length + ". Refine your search to narrow down.</div>";
    results.innerHTML = html;
    results.hidden = false;
  }

  box.disabled = true;
  box.addEventListener("input", function () { run(box.value); });
  box.addEventListener("keydown", function (ev) {
    if (ev.key === "Escape") { box.value = ""; run(""); }
    if (ev.key === "Enter") { var first = results.querySelector("a.sr-row"); if (first) first.click(); }
  });
})();
